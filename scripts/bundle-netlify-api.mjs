import * as esbuild from "esbuild";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outdir = join(root, "netlify/functions");
mkdirSync(outdir, { recursive: true });
const outfile = join(outdir, "api.cjs");

await esbuild.build({
  entryPoints: [join(root, "netlify/functions-src/api.ts")],
  outfile,
  bundle: true,
  platform: "node",
  target: "node22",
  format: "cjs",
  packages: "bundle",
  logLevel: "info",
  banner: {
    js: "// Generated by scripts/bundle-netlify-api.mjs — do not edit.",
  },
});

// Netlify Functions 2.0 looks for default export; CJS interop:
// esbuild sets module.exports.default for `export default`.
writeFileSync(
  join(outdir, "api.cjs.meta.json"),
  JSON.stringify({ bundledAt: new Date().toISOString(), outfile: "api.cjs" }, null, 2),
);

console.log("bundled", outfile);
